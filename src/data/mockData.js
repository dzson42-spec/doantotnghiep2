// Hàm sinh sơ đồ ghế (ổn định)
export const generateSeats = (showtimeId) => {
  // Tránh sinh ngẫu nhiên nếu đã lưu vào localStorage
  const localData = localStorage.getItem(`seats_${showtimeId}`);
  if (localData) {
    return JSON.parse(localData);
  }
  const seats = [];
  const rows = ["A", "B", "C", "D", "E", "F", "G", "H"];
  const cols = 12;

  rows.forEach((row, rowIndex) => {
    for (let col = 1; col <= cols; col++) {
      let type = "standard";
      let price = 80000;

      // Hàng giữa là ghế VIP
      if (rowIndex >= 3 && rowIndex <= 5 && col >= 3 && col <= 10) {
        type = "vip";
        price = 120000;
      }

      // Hàng cuối là ghế đôi
      if (rowIndex === rows.length - 1) {
        type = "couple";
        price = 200000;
      }

      // Dùng id và showtimeId để tạo pseudo-random cho mock data (giúp dữ liệu nhất quán)
      let isBooked = false;
      const charCode = showtimeId
        ? showtimeId.charCodeAt(showtimeId.length - 1)
        : 0;
      if (
        (rowIndex * cols + col + charCode) % 7 === 0 ||
        (rowIndex * cols + col + charCode) % 11 === 0
      ) {
        isBooked = true;
      }

      seats.push({
        id: `${row}${col}`,
        row,
        col,
        type,
        price,
        status: isBooked ? "booked" : "available",
      });
    }
  });

  // Lưu lại vào localStorage
  if (showtimeId) {
    localStorage.setItem(`seats_${showtimeId}`, JSON.stringify(seats));
  }

  return seats;
};

export const initialMovies = [...movies];
export const initialShowtimes = { ...showtimes };

export const getStoredMovies = () => {
  try {
    const raw = localStorage.getItem("cinevite_movies");
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    }
  } catch {
    // ignore
  }
  return initialMovies;
};

export const saveStoredMovies = (list) => {
  try {
    localStorage.setItem("cinevite_movies", JSON.stringify(list));
    window.dispatchEvent(new Event("moviesChange"));
  } catch {
    // ignore
  }
};

export const getStoredShowtimes = () => {
  try {
    const raw = localStorage.getItem("cinevite_showtimes");
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed && typeof parsed === "object") return parsed;
    }
  } catch {
    // ignore
  }
  return initialShowtimes;
};

